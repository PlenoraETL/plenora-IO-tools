"""Closed Python API inventory: source definitions plus installed runtime exposure.

No argument-name, annotation or coroutine filter. Private modules are included;
private functions/classes and function-local definitions are not public API.
The registry reviews canonical definitions, not a copied list of exports.
Runtime aliases, inherited methods and SDK-generated async delegates are
resolved by object identity; the installed wheel inventory is generated in target.
"""
import ast
import importlib
import importlib.metadata
import inspect
import json
import pkgutil
from types import CodeType
from pathlib import Path

REGISTRY = 'assurance/registries/ingressi-arrow-python.json'
CLASSES = {'ingresso guardato', 'non riceve dati Arrow esterni',
           'helper con precondizione dichiarata'}


def static_inventory(root, records):
    found = {r['id'] for r in records if r['kind'] == 'python'}

    def walk(nodes, prefix):
        for node in nodes:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if not node.name.startswith('_'):
                    found.add(prefix + '.' + node.name)
            elif isinstance(node, ast.ClassDef):
                if not node.name.startswith('_'):
                    walk(node.body, prefix + '.' + node.name)
            else:
                # Includes definitions under conditionals, without entering functions.
                walk(list(ast.iter_child_nodes(node)), prefix)

    base = root / 'sdk/python/src'
    for path in sorted((base / 'plenora_io').rglob('*.py')):
        parts = list(path.relative_to(base).with_suffix('').parts)
        if parts[-1] == '__init__':
            parts.pop()
        walk(ast.parse(path.read_text(encoding='utf-8')).body, '.'.join(parts))
    return found


def runtime_modules():
    package = importlib.import_module('plenora_io')
    distribution = importlib.metadata.distribution('plenora-io')
    installed = Path(distribution.locate_file('plenora_io/__init__.py')).resolve()
    assert Path(package.__file__).resolve() == installed, 'serve il pacchetto installato'
    native = importlib.import_module('plenora_io._native')  # mandatory, never skipped
    modules = [package, native]
    modules.extend(importlib.import_module(info.name) for info in
                   pkgutil.walk_packages(package.__path__, package.__name__ + '.'))
    return modules


def runtime_members(modules):
    return set(runtime_objects(modules))


def runtime_objects(modules):
    found = {}

    def walk(obj, prefix, ancestors=()):
        if id(obj) in ancestors:
            return
        for name, member in inspect.getmembers(obj):
            if name.startswith('_'):
                continue
            key = prefix + '.' + name
            if inspect.isroutine(member):
                found[key] = member
            elif inspect.isclass(member) and member.__module__.startswith('plenora_io'):
                walk(member, key, ancestors + (id(obj),))
            elif isinstance(member, property):
                found[key] = member
    for module in modules:
        walk(module, module.__name__)
    return found


def callable_object(value):
    if isinstance(value, (classmethod, staticmethod)):
        return value.__func__
    if isinstance(value, property):
        return value.fget
    return getattr(value, '__func__', value)


def definition_object(name, modules):
    """Resolve a discovered definition, without evaluating property getters."""
    module = max((m for m in modules if name.startswith(m.__name__ + '.')),
                 key=lambda m: len(m.__name__))
    value = module
    for part in name[len(module.__name__) + 1:].split('.'):
        value = inspect.getattr_static(value, part)
    return callable_object(value)


def auxiliary_origin(value, modules):
    owner = getattr(value, '__objclass__', None)
    module = getattr(value, '__module__', None) or getattr(owner, '__module__', None)
    name = getattr(value, '__qualname__', None)
    assert module and name, (
        'non_classificati: callable senza definizione', module, name)
    origin = module + '.' + name
    if module.startswith('plenora_io'):
        assert any(part.startswith('_') for part in name.split('.')), (
            'non_classificati: definizione pubblica non scoperta', origin)
        assert definition_object(origin, modules) is value, ('origine non autentica', origin)
    else:
        resolved = importlib.import_module(module)
        for part in name.split('.'):
            resolved = inspect.getattr_static(resolved, part)
        assert callable_object(resolved) is value, ('origine non autentica', origin)
    return origin


def runtime_origins(definitions, modules):
    """Aliases and inherited methods refer to one reviewed definition.

    Async operations are the exact wrappers generated by the SDK factory:
    code, wrapped callable and closure must all agree. Merely adding a
    __wrapped__ attribute cannot borrow another function's classification.
    """
    confine = next((m for m in modules if m.__name__ == 'plenora_io._confine'), None)
    codes = set()
    def collect(code):
        codes.add(code)
        for item in code.co_consts:
            if isinstance(item, CodeType):
                collect(item)
    if confine is not None:
        for value in vars(confine).values():
            if inspect.isfunction(value) and value.__module__ == confine.__name__:
                collect(value.__code__)
    def unconfined(value):
        seen = set()
        while getattr(value, '__code__', None) in codes and hasattr(value, '__wrapped__'):
            assert id(value) not in seen, 'ciclo nelle deleghe'
            seen.add(id(value))
            value = value.__wrapped__
        return value
    known = {}
    for name in sorted(definitions):
        value = unconfined(definition_object(name, modules))
        known.setdefault(id(value), name)
    async_module = next((m for m in modules if m.__name__ == 'plenora_io._async_client'), None)
    found = {}
    for name, raw in runtime_objects(modules).items():
        value = unconfined(callable_object(raw))
        origin = known.get(id(value))
        if origin is None and async_module is not None and inspect.iscoroutinefunction(value):
            target = unconfined(getattr(value, '__wrapped__', None))
            if id(target) in known:
                expected = async_module._async_method(value.__name__)
                assert (value.__code__ is expected.__code__
                        and target is unconfined(expected.__wrapped__)
                        and inspect.getclosurevars(value).nonlocals
                        == inspect.getclosurevars(expected).nonlocals), (
                            'non_classificati: delega async non generata', name)
                origin = known[id(target)]
        found[name] = origin or auxiliary_origin(value, modules)
    return found


def classified_runtime(registry, modules):
    assert registry['schema_version'] == 2, 'versione del registro Python'
    assert not set(registry['definitions']) & set(registry['auxiliary']), 'origini duplicate'
    origins = runtime_origins(registry['definitions'], modules)
    policy = registry['definitions'] | registry['auxiliary']
    missing = set(origins.values()) - set(policy)
    assert not missing, ('non_classificati', sorted(missing))
    for entry in policy.values():
        assert entry['classificazione'] in CLASSES and entry['motivazione'].strip()
    return {name: {'origine': origin, **policy[origin]}
            for name, origin in sorted(origins.items())}


def check(root, records, runtime=False):
    registry = json.loads((root / REGISTRY).read_text(encoding='utf-8'))
    check_entries(registry['definitions'], static_inventory(root, records), 'definitions')
    if runtime:
        return classified_runtime(registry, runtime_modules())


def check_entries(entries, found, section):
    # Explicit version conditions only for inherited standard-library methods.
    import sys
    entries = {key: entry for key, entry in entries.items()
               if tuple(entry.get('python_min', [3, 10])) <= sys.version_info[:2]}
    assert set(entries) == found, {'sezione': section,
        'non_classificati': sorted(found - set(entries)),
        'obsoleti': sorted(set(entries) - found)}
    for key, entry in entries.items():
        assert entry['classificazione'] in CLASSES and entry['motivazione'].strip(), key


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    registry = json.loads((root / REGISTRY).read_text(encoding='utf-8'))
    inventory = classified_runtime(registry, runtime_modules())
    output = root / 'target/arrow-python-runtime.json'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(inventory, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print('Inventario Python runtime installato e binding nativo: OK')
