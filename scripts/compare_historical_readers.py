"""Historical byte gate. Linux: python3 scripts/compare_historical_readers.py --old ... --new ...
Use executables built from 50f9357 and the working branch, with CARGO_BUILD_JOBS=2.
Fixtures generated by the old writer are explicitly labelled; committed independent
fixtures supplement them. FileGDB requires BOTH binaries built with GDAL support.
No output difference is accepted by default; JSON records every unavailable cell.
"""
